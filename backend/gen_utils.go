package main

import (
	"bytes"
	"fmt"

	jen "github.com/dave/jennifer/jen"
)

// GenerateGoModV2 generates a go.mod file content using jennifer/jen and returns it as a byte slice.
// Accepts a CreateProjectRequest and includes dependencies based on project type, framework, and addons.
func GenerateGoModV2(request CreateProjectRequest) ([]byte, error) {
	requiredImports := make([]string, 0)

	// Validate project type
	if !SupportedProjectTypesMap[request.ProjectType] {
		return []byte(fmt.Sprintf("// Unsupported project type: %s\n", request.ProjectType)), nil
	}

	// Validate framework for the project type
	frameworks, ok := SupportedFrameworksMap[request.ProjectType]
	if !ok || !frameworks[request.Framework] {
		return []byte(fmt.Sprintf("// Unsupported framework '%s' for project type '%s'\n", request.Framework, request.ProjectType)), nil
	}

	// Addons handling
	for addonType, addons := range request.Addons {
		if supportedAddons, exists := SupportedAddonsMap[addonType]; exists {
			for _, addon := range addons {
				if supportedAddons[addon] {
					if deps, ok := DependencyMap[addon]; ok {
						requiredImports = append(requiredImports, deps...)
					}
				}
			}
		}
	}

	// Get dependencies for the framework
	if deps, ok := DependencyMap[request.Framework]; ok {
		requiredImports = append(requiredImports, deps...)
	}

	buf := &bytes.Buffer{}
	buf.WriteString("// Code generated by go-initializer. DO NOT EDIT.\n\n")
	buf.WriteString(fmt.Sprintf("module %s\n\n", request.ModuleName))
	buf.WriteString(fmt.Sprintf("go %s\n", request.GoVersion))
	if len(requiredImports) > 0 {
		buf.WriteString("\nrequire (\n")
		for _, imp := range requiredImports {
			buf.WriteString(fmt.Sprintf("\t%s latest\n", imp))
		}
		buf.WriteString(")\n")
	}
	return buf.Bytes(), nil
}

// GenerateMainContent generates the content for main.go using jennifer/jen and returns it as a byte slice.
func GenerateMainContent() ([]byte, error) {
	f := jen.NewFile("main")
	f.PackageComment("Code generated by go-initializer. DO NOT EDIT.")
	f.Func().Id("main").Params().Block(
		jen.Qual("fmt", "Println").Call(jen.Lit("Hello from main!")),
	)
	buf := &bytes.Buffer{}
	if err := f.Render(buf); err != nil {
		return nil, fmt.Errorf("failed to render main.go: %w", err)
	}
	return buf.Bytes(), nil
}

func GenerateCacheAddon(addons []string) ([]byte, error) {
	// create a folder cache and in that create a cache.go file with sample code to connect to redis or memcached based on the addon
	for _, addon := range addons {
		switch addon {
		case "redis":
			f := jen.NewFile("cache")
			f.PackageComment("Code generated by go-initializer. DO NOT EDIT.")
			f.ImportName("github.com/redis/go-redis/v9", "redis")
			f.ImportName("context", "context")
			f.Func().Id("NewRedisClient").Params().Params(jen.Op("*").Qual("github.com/redis/go-redis/v9", "Client")).Block(
				jen.Id("rdb").Op(":=").Qual("github.com/redis/go-redis/v9", "NewClient").Params(
					jen.Id("&").Qual("github.com/redis/go-redis/v9", "Options").Values(jen.Dict{
						jen.Id("Addr"):     jen.Lit("localhost:6379"),
						jen.Id("Password"): jen.Lit(""), // no password set
						jen.Id("DB"):       jen.Lit(0),  // use default DB
					}),
				),
				jen.Return(jen.Id("rdb")),
			)
			f.Func().Id("PingRedis").Params(jen.Id("rdb").Op("*").Qual("github.com/redis/go-redis/v9", "Client")).Params(jen.Error()).Block(
				jen.Id("ctx").Op(":=").Qual("context", "Background").Call(),
				jen.Id("pong").Op(",").Op(":=").Id("rdb").Dot("Ping").Call(jen.Id("ctx")).Line(),

				jen.Qual("fmt", "Println").Call(jen.Id("pong"), jen.Lit("Redis connected successfully")),
				jen.Return(jen.Nil()),
			)
			buf := &bytes.Buffer{}
			if err := f.Render(buf); err != nil {
				return nil, fmt.Errorf("failed to render cache.go: %w", err)
			}
			return buf.Bytes(), nil
		case "memcached":
			f := jen.NewFile("cache")
			f.PackageComment("Code generated by go-initializer. DO NOT EDIT.")
			f.ImportName("github.com/bradfitz/gomemcache/memcache", "memcache")
			f.Func().Id("NewMemcacheClient").Params().Params(jen.Op("*").Qual("github.com/bradfitz/gomemcache/memcache", "Client")).Block(
				jen.Id("mc").Op(":=").Qual("github.com/bradfitz/gomemcache/memcache", "New").Call(jen.Lit("localhost:11211")),
				jen.Return(jen.Id("mc")),
			)
			buf := &bytes.Buffer{}
			if err := f.Render(buf); err != nil {
				return nil, fmt.Errorf("failed to render cache.go: %w", err)
			}
			return buf.Bytes(), nil
		default:
			return nil, fmt.Errorf("unsupported cache addon: %s", addon)
		}
	}

	return nil, nil
}
