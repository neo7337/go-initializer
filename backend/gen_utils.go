// GenerateLoggingAddon returns an internal/logger/logger.go file initialised for
// zap or logrus. The first recognised logging library found in addons is used;
// if neither is present an error is returned.
func GenerateLoggingAddon(addons []string) ([]byte, error) {
	for _, addon := range addons {
		switch addon {
		case "zap":
			return []byte(`// Code generated by go-initializer. DO NOT EDIT.
package logger

import "go.uber.org/zap"

var Log *zap.Logger

func init() {
	var err error
	Log, err = zap.NewProduction()
	if err != nil {
		panic("failed to initialise zap logger: " + err.Error())
	}
}
`), nil
		case "logrus":
			return []byte(`// Code generated by go-initializer. DO NOT EDIT.
package logger

import (
	"os"

	"github.com/sirupsen/logrus"
)

var Log = logrus.New()

func init() {
	Log.SetFormatter(&logrus.JSONFormatter{})
	Log.SetOutput(os.Stdout)
	Log.SetLevel(logrus.InfoLevel)
}
`), nil
		}
	}
	return nil, fmt.Errorf("no supported logging addon found in %v (supported: zap, logrus)", addons)
}
