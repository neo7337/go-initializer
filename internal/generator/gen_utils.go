// addToZip writes content into a new zip entry at path, eliminating the
// repeated create-then-write boilerplate across all generators.
func addToZip(zw *zip.Writer, path string, content []byte) error {
	f, err := zw.Create(path)
	if err != nil {
		return fmt.Errorf("failed to create %s in zip: %w", path, err)
	}
	if _, err = f.Write(content); err != nil {
		return fmt.Errorf("failed to write %s to zip: %w", path, err)
	}
	return nil
}

// CacheAddonGen implements AddonGenerator for the "cache" addon category.
type CacheAddonGen struct{}

func (a *CacheAddonGen) Generate(folderName string, addons []string, zw *zip.Writer) error {
	content, err := GenerateCacheAddon(addons)
	if err != nil {
		return fmt.Errorf("cache addon: %w", err)
	}
	if content == nil {
		return nil
	}
	return addToZip(zw, fmt.Sprintf("%s/internal/cache/cache.go", folderName), content)
}

