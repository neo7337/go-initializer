// GenerateGoModV2 generates a go.mod file content using jennifer/jen and returns it as a byte slice.
// Accepts a CreateProjectRequest and includes dependencies based on project type, framework, and addons.
func GenerateGoModV2(request CreateProjectRequest) ([]byte, error) {
	requiredImports := make([]string, 0)

	// Validate project type
	if !SupportedProjectTypesMap[request.ProjectType] {
		return nil, fmt.Errorf("unsupported project type: %s", request.ProjectType)
	}

	// Validate framework for the project type
	frameworks, ok := SupportedFrameworksMap[request.ProjectType]
	if !ok || !frameworks[request.Framework] {
		return nil, fmt.Errorf("unsupported framework '%s' for project type '%s'", request.Framework, request.ProjectType)
	}

	// Addons handling
	for addonType, addons := range request.Addons {
		if supportedAddons, exists := SupportedAddonsMap[addonType]; exists {
			for _, addon := range addons {
				if supportedAddons[addon] {
					if deps, ok := DependencyMap[addon]; ok {
						requiredImports = append(requiredImports, deps...)
					}
				}
			}
		}
	}

	// Get dependencies for the framework
	if deps, ok := DependencyMap[request.Framework]; ok {
		requiredImports = append(requiredImports, deps...)
	}

	buf := &bytes.Buffer{}
	buf.WriteString("// Code generated by go-initializer. DO NOT EDIT.\n\n")
	buf.WriteString(fmt.Sprintf("module %s\n\n", request.ModuleName))
	buf.WriteString(fmt.Sprintf("go %s\n", request.GoVersion))
	if len(requiredImports) > 0 {
		buf.WriteString("\nrequire (\n")
		for _, imp := range requiredImports {
			buf.WriteString(fmt.Sprintf("\t%s\n", imp))
		}
		buf.WriteString(")\n")
	}
	return buf.Bytes(), nil
}

